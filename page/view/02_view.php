<script>
  var iconBell = document.getElementById("bell");
  if(iconBell) {
    iconBell.addEventListener("click", function (e) {
    		window.location.href = "07_notification.php"
    });
  }
  // 탭 버튼들
  const tabButtons = document.querySelectorAll('.tab-btn');
  const listAll = document.getElementById('list-all');
  const listProject = document.getElementById('list-project');
  const listDirect = document.getElementById('list-direct');

  // 초기 상태: 전체 탭 활성화
  setActiveTab('all');

  tabButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      const tab = btn.getAttribute('data-tab');
      setActiveTab(tab);
    });
  });

  function setActiveTab(tab) {
    // 1) 리스트 표시/숨김
    if (tab === 'all') {
      listAll.style.display = 'flex';
      listProject.style.display = 'none';
      listDirect.style.display = 'none';
    } else if (tab === 'project') {
      listAll.style.display = 'none';
      listProject.style.display = 'flex';
      listDirect.style.display = 'none';
    } else if (tab === 'direct') {
      listAll.style.display = 'none';
      listProject.style.display = 'none';
      listDirect.style.display = 'flex';
    }

    // 2) 탭 스타일 초기화
    tabButtons.forEach(btn => {
      const text = btn.querySelector('.text1, .text2');
      btn.style.background = 'white';
      if (text) {
        text.style.color = '#99A1AF';
        text.style.fontWeight = '400';
      }
    });

    // 3) 선택된 탭만 활성 스타일
    const activeBtn = document.querySelector(`.tab-btn[data-tab="${tab}"]`);
    if (activeBtn) {
      const activeText = activeBtn.querySelector('.text1, .text2');
      activeBtn.style.background = '#1E78FF';
      if (activeText) {
        activeText.style.color = 'white';
        activeText.style.fontWeight = '700';
      }
    }
  }
	["chatting", "chatting1"].forEach(function(id) {
	var el = document.getElementById(id);
	if (el) {
		el.addEventListener("click", function () {
		window.location.href = "02_01_chatting.php";
		});
	}
	});

</script>
