<script>
    // ============================
    // 탭 요소
    // ============================
    const tabDev    = document.getElementById("tab-dev");
    const tabDesign = document.getElementById("tab-design");
    const tabPm     = document.getElementById("tab-pm");

    // 리스트 영역
    const devList      = document.getElementById("dev-list");
    const designerList = document.getElementById("designer-list");
    const pmList       = document.getElementById("pm-list");

    // 탭 컨테이너
    const tabContainer = document.querySelector(".main-content .container2");

    // ============================
    // 바텀시트 Popup
    // ============================
    const popupSheet  = document.getElementById("popup-dev");    // overlay
    const sheetIframe = document.querySelector(".popup-iframe"); // iframe

    // 필터 박스들
    const filterDomain  = document.getElementById("frameContainer");   // 관심 도메인
    const filterPurpose = document.getElementById("frameContainer1"); // 목적
    const filterTool    = document.getElementById("frameContainer2"); // 사용하는 툴

    // ============================
    // 개발자 카드 DOM (특정 5명 필터용)
    // ============================
    const devCards = document.querySelectorAll("#dev-list > .container3");

    // #dev-list 기준 인덱스 (0부터 시작)
    // 0: 최수민
    // 1: 박현우
    // 2: 김민석
    // 3: 한승우
    // 4: 오지훈
    // 5: 서유진
    // 6: 남궁현
    // 7: 배연주
    // 8: 김동현
    // 9: 이수진
    // 10: 박도현
    // 11: 이준혁
    // 12: 최은영
    // 13: 정민호
    // 14: 강서준
    // 15: 윤소연
    // 16: 임성민
    // 17: 송현주
    // 18: 오동훈
    const devFiveIndices = [5, 11, 14, 16, 17]; // 서유진, 이준혁, 강서준, 임성민, 송현주

    // 전체 개발자 보이기 - 원래 CSS display를 그대로 쓰기 위해 "" 로 복원
    function showAllDevelopers() {
        devCards.forEach(card => {
            card.style.display = ""; // ★ flex 레이아웃 유지 (block으로 바꾸지 않음)
        });
    }

    // 특정 5명만 보이기 - 나머지는 display:none
    function showFiveDevelopers() {
        devCards.forEach((card, index) => {
            if (devFiveIndices.includes(index)) {
                card.style.display = "";     // 원래 CSS대로 (flex) 유지
            } else {
                card.style.display = "none"; // 완전히 숨김
            }
        });
    }

    // ============================
    // 바텀시트 → 부모로 postMessage 받기
    // ============================
    window.addEventListener("message", (event) => {
        if (!event.data || !event.data.mode) return;

        if (event.data.mode === "five") {
            showFiveDevelopers();
        } else if (event.data.mode === "all") {
            showAllDevelopers();
        }

        closeFilterSheet();
    });

    // ============================
    // 탭 전환 함수
    // ============================
    function setTab(target) {

        // 리스트 보이기 / 숨기기
        devList.style.display      = target === "dev"    ? "block" : "none";
        designerList.style.display = target === "design" ? "block" : "none";
        pmList.style.display       = target === "pm"     ? "block" : "none";

        // 탭 active 제거
        tabDev.classList.remove("active-tab");
        tabDesign.classList.remove("active-tab");
        tabPm.classList.remove("active-tab");

        // 선택된 탭 활성화
        if (target === "dev")    tabDev.classList.add("active-tab");
        if (target === "design") tabDesign.classList.add("active-tab");
        if (target === "pm")     tabPm.classList.add("active-tab");

        // 배경 스타일 변경
        tabContainer.classList.remove("mode-dev", "mode-design", "mode-pm");
        if (target === "dev")    tabContainer.classList.add("mode-dev");
        if (target === "design") tabContainer.classList.add("mode-design");
        if (target === "pm")     tabContainer.classList.add("mode-pm");

        // 개발자 탭으로 돌아올 때는 전체 보기로 리셋
        if (target === "dev") {
            showAllDevelopers();
        }
    }

    // 초기 탭: 개발자
    setTab("dev");


    // ============================
    // 탭 클릭 이벤트
    // ============================
    tabDev.addEventListener("click", () => {
        setTab("dev");
        popupSheet.style.display = "none";
    });

    tabDesign.addEventListener("click", () => {
        setTab("design");
        popupSheet.style.display = "none";
    });

    tabPm.addEventListener("click", () => {
        setTab("pm");
        popupSheet.style.display = "none";
    });


    // ============================
    // 바텀시트 열기 (도메인, 목적, 툴)
    // ============================
    function openFilterSheet(type) {
        if (!popupSheet || !sheetIframe) return;

        sheetIframe.src = "view/06_view_sheet.php?tab=" + type;
        popupSheet.style.display = "flex";
    }

    // 각각의 필터 박스 클릭 시
    filterDomain.addEventListener("click", () => openFilterSheet("domain"));
    filterPurpose.addEventListener("click", () => openFilterSheet("purpose"));
    filterTool.addEventListener("click", () => openFilterSheet("tools"));

    // =============================
    // 바텀시트 닫기 함수
    // =============================
    function closeFilterSheet() {
        if (!popupSheet || !sheetIframe) return;

        const sheet = document.querySelector(".popup-sheet");
        if (!sheet) {
            popupSheet.style.display = "none";
            return;
        }

        sheet.classList.add("closing");

        const handleAnimationEnd = function () {
            sheet.classList.remove("closing");
            popupSheet.style.display = "none";
            sheetIframe.src = "";

            sheet.removeEventListener("animationend", handleAnimationEnd);
        };

        sheet.addEventListener("animationend", handleAnimationEnd);
    }

    // =============================
    // 오버레이 클릭 시 닫기
    // =============================
    popupSheet.addEventListener("click", function(e) {
        if (e.target === popupSheet) {
            closeFilterSheet();
        }
    });

    // ============================
    // 뒤로가기 / 제안하기 버튼
    // ============================
    const backBtn    = document.getElementById("back");
    const suggestBtn = document.getElementById("suggest");

    if (backBtn) {
        backBtn.addEventListener("click", () => {
            window.location.href = "01_project.php";
        });
    }

    if (suggestBtn) {
        suggestBtn.addEventListener("click", () => {
            window.location.href = "06_01_teammate.php";
        });
    }
</script>
