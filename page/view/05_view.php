    if (event.data.action === "resetFilter") {
      mainList.innerHTML = originalProjectListHTML;

      // ★ 복원된 카드에도 이벤트 다시 연결
      bindProjectCardEvents();
    }
  });

  // 페이지 로딩 시 최초 한 번 이벤트 연결
  bindProjectCardEvents();
