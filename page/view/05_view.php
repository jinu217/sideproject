  // =============================
  // 프로젝트 카드 클릭 이벤트 연결 함수
  // =============================
  function bindProjectCardEvents() {
    var project_dummy = document.getElementById("project-dummy");
    if (project_dummy) {
      project_dummy.addEventListener("click", function (e) {
        window.location.href = "08_project_detail.php";
      });
    }
  }

  // =============================
  // 프로젝트 리스트 초기 상태 저장
  // =============================
  const mainList = document.querySelector(".main-content .container2");
  const originalProjectListHTML = mainList ? mainList.innerHTML : "";

  // 필터 적용 시 보여줄 3개 카드(초기 DOM에서 한 번만 가져오기)
  let card25HTML = "";
  let card36HTML = "";
  let card47HTML = "";

  if (mainList) {
    const card25 = mainList.querySelector(".container91");
    const card36 = mainList.querySelector(".container196");
    const card47 = mainList.querySelector(".container356");

    card25HTML = card25 ? card25.outerHTML : "";
    card36HTML = card36 ? card36.outerHTML : "";
    card47HTML = card47 ? card47.outerHTML : "";
  }

  // =============================
  // 바텀시트에서 오는 메시지 처리
  // =============================
  window.addEventListener("message", function(event) {
    if (!event.data || !event.data.action) return;
    if (!mainList) return;

    // 1) 필터 적용: 3개 카드만 남기기
    if (event.data.action === "applyFilter") {
      mainList.innerHTML = card25HTML + card36HTML + card47HTML;

      // ★ 새로 그려진 카드에 이벤트 다시 연결
      bindProjectCardEvents();
    }

