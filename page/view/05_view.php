  var popupcomponent7Container = document.getElementById("popupcomponent7Container");
  if (popupcomponent7Container) {
    popupcomponent7Container.addEventListener("click", function (e) {
      window.location.href = "./Container.html";
    });
  }

  var popupcomponent5Container = document.getElementById("popupcomponent5Container");
  if (popupcomponent5Container) {
    popupcomponent5Container.addEventListener("click", function (e) {
      window.location.href = "./Container2.html";
    });
  }

