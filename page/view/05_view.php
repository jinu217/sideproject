  const popupSheet  = document.getElementById("popup-project");
  const sheetIframe = document.querySelector(".popup-iframe");

  // 필터 버튼 (도메인 / 포지션 / 목적)
  const filterDomain   = document.getElementById("frameContainer");
  const filterPosition = document.getElementById("frameContainer1");
  const filterPurpose  = document.getElementById("frameContainer2");

  // =============================
  // 바텀시트 열기 함수
  // =============================
  function openFilterSheet(type) {
    if (!popupSheet || !sheetIframe) return;

    sheetIframe.src = "view/05_view_sheet.php?tab=" + type;
    popupSheet.style.display = "flex";
  }

  // =============================
  // 클릭 시 바텀시트 열기
  // =============================
  if (filterDomain) {
    filterDomain.addEventListener("click", () => openFilterSheet("domain"));
  }
  if (filterPosition) {
    filterPosition.addEventListener("click", () => openFilterSheet("position"));
  }
  if (filterPurpose) {
    filterPurpose.addEventListener("click", () => openFilterSheet("purpose"));
  }

  // =============================
  // 바텀시트 닫기 함수
  // =============================
  function closeFilterSheet() {
    if (!popupSheet || !sheetIframe) return;

    const sheet = document.querySelector(".popup-sheet");
    if (!sheet) {
      popupSheet.style.display = "none";
      return;
    }

    // 닫히는 애니메이션 클래스 추가
    sheet.classList.add("closing");

    // 애니메이션이 끝난 뒤에 display:none 처리
    const handleAnimationEnd = function () {
      sheet.classList.remove("closing");
      popupSheet.style.display = "none";
      sheetIframe.src = ""; // 필요 없으면 이 줄은 지워도 됨

      sheet.removeEventListener("animationend", handleAnimationEnd);
    };

    sheet.addEventListener("animationend", handleAnimationEnd);
  }

  // =============================
  // 오버레이 클릭 시 닫기
  // =============================
  if (popupSheet) {
    popupSheet.addEventListener("click", function(e) {
      if (e.target === popupSheet) {
        closeFilterSheet();
      }
    });
  }

  // =============================
  // 상단 뒤로가기 및 기타 버튼
  // =============================
  var arrowBackIosNewIcon = document.getElementById("back");
  if (arrowBackIosNewIcon) {
    arrowBackIosNewIcon.addEventListener("click", function (e) {
      window.location.href = "01_project.php";
    });
  }

  var popupcomponent6Container = document.getElementById("popupcomponent6Container");
  if (popupcomponent6Container) {
    popupcomponent6Container.addEventListener("click", function (e) {
      window.location.href = "./Container1.html";
    });
